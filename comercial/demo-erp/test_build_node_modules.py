#!/usr/bin/env python3
"""build.py en una copia sin node_modules (15-oct-2026, deploy-axw): limpia_publico.js caía con «Cannot find module 'terser'».

    python test_build_node_modules.py

Hermético: un repo de juguete en un temporal con un worktree con OTRO nombre (como una copia del scratchpad). Mide que
`build.node_modules_de_fuera` encuentra el node_modules del clon principal desde el worktree, que en el principal no
añade nada, y que `build.limpia_publico` dice claro qué módulo falta y dónde instalarlo en vez de dejar solo la traza.
"""
import os
import shutil
import subprocess
import sys
import tempfile

AQUI = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, AQUI)
import build  # noqa: E402

fallos = 0


def mira(que, ok):
    global fallos
    print(('ok   ' if ok else 'FALLA ') + que)
    fallos += 0 if ok else 1


def g(*a, cwd=None):
    subprocess.run(['git', *a], cwd=cwd, capture_output=True, text=True, check=True)


t = tempfile.mkdtemp()
try:
    principal, copia = os.path.join(t, 'AxisWorks'), os.path.join(t, 'fuera', 'axw')
    sub = os.path.join('comercial', 'demo-erp')
    os.makedirs(os.path.join(principal, sub))
    open(os.path.join(principal, sub, 'package.json'), 'w').close()
    g('init', '-q', principal)
    g('-C', principal, 'add', '-A')
    g('-C', principal, '-c', 'user.name=t', '-c', 'user.email=t@t', 'commit', '-q', '-m', 'x')
    g('-C', principal, 'worktree', 'add', '-q', '--detach', copia)
    nm = os.path.join(principal, sub, 'node_modules')
    os.makedirs(nm)
    mira('node_modules VACÍO en el principal: no cuenta', build.node_modules_de_fuera(os.path.join(copia, sub)) is None)
    open(os.path.join(nm, '.package-lock.json'), 'w').close()
    de_fuera = build.node_modules_de_fuera(os.path.join(copia, sub))
    mira('desde un worktree con otro nombre encuentra el node_modules del clon principal',
         de_fuera is not None and os.path.normcase(os.path.normpath(de_fuera)) == os.path.normcase(os.path.normpath(nm)))
    mira('en el clon principal (ya completo) no añade nada', build.node_modules_de_fuera(os.path.join(principal, sub)) is None)
    mira('fuera de git no revienta', build.node_modules_de_fuera(os.path.join(t, 'fuera')) is None)
finally:
    shutil.rmtree(t, ignore_errors=True)

# limpia_publico sin sus módulos: un `node` falso que contesta lo que contesta node cuando no encuentra terser.
real = build.subprocess.run


class _R:
    returncode, stdout = 1, ''
    stderr = "Error: Cannot find module 'terser'\nRequire stack:\n- limpia_publico.js"


build.subprocess.run = lambda *a, **k: _R()
try:
    try:
        import io
        import contextlib
        salida = io.StringIO()
        with contextlib.redirect_stdout(salida), contextlib.redirect_stderr(io.StringIO()):
            build.limpia_publico('dist')
        msg, paro = '', False
    except SystemExit:
        msg, paro = salida.getvalue(), True
    mira("sin terser el build PARA y dice qué módulo falta y que es npm ci", paro and "'terser'" in msg and 'npm ci' in msg)
finally:
    build.subprocess.run = real

print(('OK' if not fallos else 'FALLA') + ' test_build_node_modules' + ('' if not fallos else ': %d' % fallos))
sys.exit(1 if fallos else 0)
